#!/usr/bin/env node
/**
 * Generates packages/shared/src/config/themes.ts from the read-only design showcase.
 * The design files are the visual authority; the generated config is the runtime
 * source for the four switchable themes (all colours are tokens, never hard-coded
 * in components).
 *
 * The render function is exported so `scripts/check-design.mjs` can verify the
 * committed output is byte-identical to what the design sources produce.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const assets = resolve(root, 'opencode-workflow-design-showcase/originals/main/assets');

const ids = ['deepseek', 'warm', 'spdb', 'github-white'];
const labels = {
  deepseek: ['DeepSeek', '深色默认主题', 'dark'],
  warm: ['Warm', '暖色 Claude 风', 'light'],
  spdb: ['SPDB', '浦发银行风', 'light'],
  'github-white': ['GitHub White', 'GitHub 浅色', 'light'],
};

function declarations(block) {
  const tokens = {};
  for (const match of block.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
    tokens[match[1]] = match[2].trim();
  }
  return tokens;
}

function blockFor(skins, skin) {
  const marker = `[data-skin="${skin}"]`;
  const start = skins.indexOf(marker);
  if (start < 0) throw new Error(`missing skin ${skin}`);
  const open = skins.indexOf('{', start);
  const close = skins.indexOf('}', open);
  return skins.slice(open + 1, close);
}

/**
 * Reads the design assets and renders the complete themes.ts text.
 * No files are written; used by both the generator CLI and the design check.
 */
export function renderThemeConfig() {
  const skins = readFileSync(resolve(assets, 'skins.css'), 'utf8');
  const ds = readFileSync(resolve(assets, 'ds.css'), 'utf8');

  const rootMatch = ds.match(/:root\{([\s\S]*?)\n\}/);
  if (!rootMatch) throw new Error('missing :root in ds.css');
  const baseAll = declarations(rootMatch[1]);

  const themeTokens = {};
  for (const id of ids) themeTokens[id] = declarations(blockFor(skins, id));

  const baseTokens = {};
  for (const [key, value] of Object.entries(baseAll)) {
    if (!Object.hasOwn(themeTokens.deepseek, key)) baseTokens[key] = value;
  }

  const tokenNames = [...new Set([...Object.keys(themeTokens.deepseek), ...Object.keys(themeTokens.warm), ...Object.keys(themeTokens.spdb), ...Object.keys(themeTokens['github-white'])])].sort();
  const baseNames = Object.keys(baseTokens).sort();

  const serialise = (record) =>
    '{\n' +
    Object.entries(record)
      .map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
      .join('\n') +
    '\n  }';

  const output = `/* AUTO-GENERATED by scripts/generate-theme-config.mjs — do not edit by hand.
 * Source of truth: opencode-workflow-design-showcase/originals/main/assets/{ds,skins}.css
 * Four themes are pure configuration: switching a theme only swaps CSS variables. */

import type { ThemeIdValue } from '../domain/enums.ts';

export interface ThemeConfig {
  readonly id: ThemeIdValue;
  readonly label: string;
  readonly description: string;
  readonly colorScheme: 'dark' | 'light';
  /** All colour/effect tokens that differ from the base design system. */
  readonly tokens: Readonly<Record<string, string>>;
}

/** Structural tokens shared by every theme (fonts, spacing, radii, sizes). */
export const BASE_TOKENS = ${serialise(baseTokens)} as const;

export const THEME_TOKEN_NAMES = ${JSON.stringify(tokenNames, null, 0)} as const;
export type ThemeTokenName = (typeof THEME_TOKEN_NAMES)[number];

export const THEME_CONFIGS: Readonly<Record<ThemeIdValue, ThemeConfig>> = {
  deepseek: {
    id: 'deepseek',
    label: ${JSON.stringify(labels.deepseek[0])},
    description: ${JSON.stringify(labels.deepseek[1])},
    colorScheme: ${JSON.stringify(labels.deepseek[2])},
    tokens: ${serialise(themeTokens.deepseek)},
  },
  warm: {
    id: 'warm',
    label: ${JSON.stringify(labels.warm[0])},
    description: ${JSON.stringify(labels.warm[1])},
    colorScheme: ${JSON.stringify(labels.warm[2])},
    tokens: ${serialise(themeTokens.warm)},
  },
  spdb: {
    id: 'spdb',
    label: ${JSON.stringify(labels.spdb[0])},
    description: ${JSON.stringify(labels.spdb[1])},
    colorScheme: ${JSON.stringify(labels.spdb[2])},
    tokens: ${serialise(themeTokens.spdb)},
  },
  'github-white': {
    id: 'github-white',
    label: ${JSON.stringify(labels['github-white'][0])},
    description: ${JSON.stringify(labels['github-white'][1])},
    colorScheme: ${JSON.stringify(labels['github-white'][2])},
    tokens: ${serialise(themeTokens['github-white'])},
  },
};

export const THEME_IDS = ${JSON.stringify(ids)} as const;

export function themeCssVariables(theme: ThemeIdValue): Record<string, string> {
  const config = THEME_CONFIGS[theme] ?? THEME_CONFIGS.deepseek;
  return { ...BASE_TOKENS, ...config.tokens };
}

export function nextTheme(current: ThemeIdValue, direction: 1 | -1 = 1): ThemeIdValue {
  const index = THEME_IDS.indexOf(current);
  const next = (index + direction + THEME_IDS.length) % THEME_IDS.length;
  return THEME_IDS[next] ?? current;
}
`;

  return { output, tokenNames, baseNames };
}

function main() {
  const { output, tokenNames, baseNames } = renderThemeConfig();
  writeFileSync(resolve(root, 'packages/shared/src/config/themes.ts'), output);
  console.log(`wrote themes.ts: ${tokenNames.length} theme tokens, ${baseNames.length} base tokens`);
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (invokedDirectly) main();
