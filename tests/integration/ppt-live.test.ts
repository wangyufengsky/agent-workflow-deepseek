import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApplication } from '../../packages/server/src/index.ts';

const LIVE = process.env.AGENT_WORKFLOW_LIVE === '1';

function requestKey(prefix: string): string {
  return `req_${prefix}${Math.random().toString(36).slice(2, 21)}`;
}

test('live: PPT outline is generated by the managed model and persisted', { skip: !LIVE, timeout: 180_000 }, async () => {
  const app = await createApplication({ dataDir: mkdtempSync(join(tmpdir(), 'aw-ppt-live-')), port: 0, host: '127.0.0.1' });
  try {
    assert.ok(app.adapter);
    await app.adapter.ensureReady();
    const created = await app.app.inject({
      method: 'POST',
      url: '/api/ppt/works',
      payload: { requestKey: requestKey('ppt'), title: '季度汇报', topic: '本季度交付、质量与下季度计划', confirmCreate: true },
    });
    assert.equal(created.statusCode, 200, created.body);
    const work = created.json().data.resource[0] as { id: string };
    const generated = await app.app.inject({
      method: 'POST',
      url: `/api/ppt/works/${work.id}/generate`,
      payload: { requestKey: requestKey('gen'), confirmGenerate: true },
    });
    assert.equal(generated.statusCode, 200, generated.body);
    const result = generated.json().data.resource as { status: string; outline: string[] };
    console.log('[ppt-live]', JSON.stringify({ status: result.status, slides: result.outline.length, outline: result.outline.slice(0, 4) }));
    assert.equal(result.status, 'ready');
    assert.ok(result.outline.length >= 3);
    const listed = await app.app.inject({ method: 'GET', url: '/api/ppt/works' });
    assert.equal((listed.json().data.works as { outline: string[] }[])[0]!.outline.length, result.outline.length);
  } finally {
    await app.close();
  }
});
