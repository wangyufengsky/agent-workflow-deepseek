import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Store } from '@agent-workflow/storage';
import { Engine, type OpenCodePort } from '../../packages/engine/src/index.ts';
import { GitCliAdapter } from '../../packages/server/src/adapters/git-cli.ts';
import type { PlanGraph, PlanNode } from '@agent-workflow/shared';

// Real local Git/filesystem snapshots; no model, network, or remote Git writes.
test('failed-stage recovery copies its frontier, frozen roles and actual uncommitted output into an isolated Git worktree', async () => {
  const root = mkdtempSync(join(tmpdir(), 'aw-recovery-context-'));
  const repo = join(root, 'repo');
  execFileSync('git', ['init', '-q', '-b', 'main', repo]);
  execFileSync('git', ['config', 'user.email', 'test@example.com'], { cwd: repo });
  execFileSync('git', ['config', 'user.name', 'Test'], { cwd: repo });
  writeFileSync(join(repo, 'source.txt'), 'baseline');
  writeFileSync(join(repo, 'deleted.txt'), 'delete in parent');
  execFileSync('git', ['add', '.'], { cwd: repo });
  execFileSync('git', ['commit', '-qm', 'baseline'], { cwd: repo });
  const sha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repo, encoding: 'utf8' }).trim();
  const store = new Store({ dataDir: join(root, 'data') });
  const git = new GitCliAdapter(30000, join(root, 'merge'));
  const opencode: OpenCodePort = { status: () => ({ state: 'stopped' }), ensureReady: async () => {}, runSession: async () => { throw new Error('test must never dispatch model'); }, abortSession: async () => {}, findSessions: async () => [] };
  const engine = new Engine({ store, ports: { git, opencode } });
  const project = store.projects.create({ name: 'recovery', rootPath: repo, gitState: 'git', defaultBranch: 'main' });
  const parent = store.tasks.create({ projectId: project.id, title: 'parent', requirementText: 'keep context', methodId: 'method.requirement-development', methodRevision: 'r12' });
  const role = structuredClone(engine.catalog.roles.find((item) => item.id === 'role.developer')!);
  const node = (id: string): PlanNode => Object.assign({ id, key: id, title: id, kind: 'implementation' as const, groupId: 'g', summary: '', inputs: [], outputs: [], acceptance: [], resources: { read: [], write: [] }, roleId: role.id }, { roleSnapshot: role });
  const graph: PlanGraph = { nodes: [node('done'), node('failed'), node('future')], edges: [{ id: 'df', from: 'done', to: 'failed', kind: 'order' }, { id: 'ff', from: 'failed', to: 'future', kind: 'order' }], groups: [{ id: 'g', label: 'g', kind: 'implementation', refined: true, collapsible: false, collapsedByDefault: false }] };
  const plan = store.plans.create({ taskId: parent.id, source: 'manual', graph, status: 'confirmed' });
  const execution = store.executions.create({ taskId: parent.id, planRevisionId: plan.id, graph, autoAdvance: false });
  store.executions.updateNode(execution.id, 'done', { status: 'succeeded' });
  store.executions.updateNode(execution.id, 'failed', { status: 'failed', error: { code: 'VALIDATION_FAILED', message: 'retry this frontier' } });
  store.executions.update(execution.id, { status: 'failed' });
  store.settings.putJson(`execution.settings.${execution.id}`, { ...engine.settings.execution, maxAttempts: 2 });
  const attempt = store.executions.createAttempt({ executionId: execution.id, nodeId: 'done', ordinal: 1 });
  store.executions.finishAttempt(attempt.id, 'succeeded', { resultRevision: 'res_prior', summary: 'real snapshot file is the prior output', artifacts: [], errors: [], warnings: [] });
  const handle = await git.createWorktree({ repoRoot: repo, worktreesRoot: join(root, 'parent-worktrees'), taskId: parent.id, baseRef: 'main', baseSha: sha, branch: 'task/parent' });
  const workspace = store.workspaces.create({ taskId: parent.id, kind: 'git_worktree', displayRoot: handle.path, originalRootDisplay: repo, baseRef: 'main' });
  store.workspaces.update(workspace.id, { state: 'ready', baseSha: sha, branch: handle.branch, worktreeHandle: handle.handle });
  store.tasks.update(parent.id, { stage: 'executing', attention: 'failed', currentPlanRevisionId: plan.id, executionId: execution.id, workspaceId: workspace.id });
  writeFileSync(join(handle.path, 'source.txt'), 'parent partial output');
  writeFileSync(join(handle.path, 'untracked.txt'), 'prior-stage artifact');
  rmSync(join(handle.path, 'deleted.txt'));

  const first = await engine.recoveries.create(parent.id, { requestKey: 'req_context_recovery', mode: 'from_failed_stage', confirmCreate: true });
  assert.equal(first.receipt.status, 'succeeded');
  const derived = first.resource!.task;
  assert.equal(derived.stage, 'confirming');
  const copied = store.plans.get(derived.currentPlanRevisionId!)!;
  assert.equal(copied.status, 'unconfirmed');
  assert.equal(copied.baseRevisionId, plan.id);
  assert.deepEqual(copied.graph.nodes.map((item) => item.id), ['failed', 'future']);
  assert.deepEqual(copied.graph.nodes[0], graph.nodes[1]);
  assert.match(derived.requirement.supplements.at(-1)!.text, new RegExp(attempt.id));
  const isolated = store.workspaces.get(derived.workspaceId!)!;
  assert.notEqual(isolated.displayRoot, handle.path);
  assert.notEqual(isolated.branch, handle.branch);
  assert.equal(readFileSync(join(isolated.displayRoot!, 'source.txt'), 'utf8'), 'parent partial output');
  assert.equal(readFileSync(join(isolated.displayRoot!, 'untracked.txt'), 'utf8'), 'prior-stage artifact');
  assert.throws(() => readFileSync(join(isolated.displayRoot!, 'deleted.txt')));
  writeFileSync(join(isolated.displayRoot!, 'source.txt'), 'derived edit');
  assert.equal(readFileSync(join(handle.path, 'source.txt'), 'utf8'), 'parent partial output');
  assert.equal(readFileSync(join(repo, 'source.txt'), 'utf8'), 'baseline');
  assert.equal((await engine.recoveries.create(parent.id, { requestKey: 'req_context_recovery', mode: 'from_failed_stage', confirmCreate: true })).resource!.task.id, derived.id);
  assert.equal(store.executions.byTask(derived.id), undefined, 'confirmation is still required');
  engine.plans.confirm(derived.id, { requestKey: 'req_context_confirm', planRevisionId: copied.id, expectedRevisionNumber: copied.revisionNumber, confirmPlan: true });
  const nextExecution = store.executions.byTask(derived.id)!;
  assert.deepEqual(nextExecution.nodes.map((item) => item.nodeId), ['failed', 'future']);
  assert.equal(store.settings.getJson<{ maxAttempts: number }>(`execution.settings.${nextExecution.id}`)?.maxAttempts, 2);

  const full = await engine.recoveries.create(parent.id, { requestKey: 'req_context_all', mode: 'all_stages', confirmCreate: true });
  assert.equal(store.plans.get(full.resource!.task.currentPlanRevisionId!)!.graph.nodes.length, 3);
  const fullWorkspace = store.workspaces.get(full.resource!.task.workspaceId!)!;
  assert.equal(readFileSync(join(fullWorkspace.displayRoot!, 'source.txt'), 'utf8'), 'baseline');
  assert.equal(readFileSync(join(fullWorkspace.displayRoot!, 'deleted.txt'), 'utf8'), 'delete in parent');
  assert.equal(store.executions.get(execution.id)?.status, 'failed');
  symlinkSync(join(repo, 'source.txt'), join(handle.path, 'external-link'));
  await assert.rejects(engine.recoveries.create(parent.id, { requestKey: 'req_context_symlink', mode: 'from_failed_stage', confirmCreate: true }), /符号链接/);
  assert.equal(engine.commands.get('req_context_symlink')?.status, 'failed');
  const partial = engine.recoveries.list(parent.id).recoveries.find((record) => store.settings.getJson<{ requestKey: string }>(`task.recovery.${record.taskId}`)?.requestKey === 'req_context_symlink')!;
  assert.ok(partial, 'failed local snapshot keeps lineage and its partial workspace for audit');
  assert.equal(store.workspaces.byTask(partial.taskId)?.state, 'blocked');
  assert.equal(readFileSync(join(repo, 'source.txt'), 'utf8'), 'baseline');
  store.close();
});


test('directory recovery retains the original three-way baseline and rejects unknown source executions', async () => {
  const root = mkdtempSync(join(tmpdir(), 'aw-recovery-copy-'));
  const projectRoot = join(root, 'source');
  mkdirSync(projectRoot, { recursive: true });
  writeFileSync(join(projectRoot, 'data.txt'), 'original baseline');
  const store = new Store({ dataDir: join(root, 'data') });
  const git = new GitCliAdapter(30000, join(root, 'merge'));
  const opencode: OpenCodePort = { status: () => ({ state: 'stopped' }), ensureReady: async () => {}, runSession: async () => { throw new Error('no model'); }, abortSession: async () => {}, findSessions: async () => [] };
  const engine = new Engine({ store, ports: { git, opencode } });
  const project = store.projects.create({ name: 'copy', rootPath: projectRoot, gitState: 'not_git' });
  const task = store.tasks.create({ projectId: project.id, title: 'copy', requirementText: 'context', methodId: 'method.requirement-development', methodRevision: 'r12' });
  const graph: PlanGraph = { nodes: [{ id: 'failed', key: 'failed', title: 'failed', kind: 'implementation', groupId: 'g', summary: '', inputs: [], outputs: [], acceptance: [], resources: { read: [], write: [] } }], edges: [], groups: [] };
  const plan = store.plans.create({ taskId: task.id, source: 'manual', graph, status: 'confirmed' });
  store.tasks.update(task.id, { currentPlanRevisionId: plan.id });
  const prepared = await engine.workspaces.prepare(task.id, { requestKey: 'req_copy_prepare', confirmPrepare: true, expectedPlanRevisionNumber: 1 });
  const workspace = prepared.resource!.workspace;
  const execution = store.executions.create({ taskId: task.id, planRevisionId: plan.id, graph, autoAdvance: false });
  store.executions.updateNode(execution.id, 'failed', { status: 'failed' });
  store.executions.update(execution.id, { status: 'unknown' });
  store.tasks.update(task.id, { executionId: execution.id, workspaceId: workspace.id, attention: 'unknown' });
  await assert.rejects(engine.recoveries.create(task.id, { requestKey: 'req_copy_unknown', mode: 'from_failed_stage', confirmCreate: true }), /未知结果/);
  store.executions.update(execution.id, { status: 'failed' });
  store.tasks.update(task.id, { attention: 'failed' });
  writeFileSync(join(workspace.displayRoot!, 'data.txt'), 'partial work');
  const recovered = await engine.recoveries.create(task.id, { requestKey: 'req_copy_recovery', mode: 'from_failed_stage', confirmCreate: true });
  const target = store.workspaces.get(recovered.resource!.task.workspaceId!)!;
  assert.equal(readFileSync(join(target.displayRoot!, 'data.txt'), 'utf8'), 'partial work');
  const baseline = store.settings.getJson<{ baselineRoot: string }>(`directory.baseline.${target.id}`)!;
  assert.equal(readFileSync(join(baseline.baselineRoot, 'data.txt'), 'utf8'), 'original baseline');
  assert.equal(readFileSync(join(projectRoot, 'data.txt'), 'utf8'), 'original baseline');
  assert.equal(readFileSync(join(workspace.displayRoot!, 'data.txt'), 'utf8'), 'partial work');
  store.close();
});
